'use client'

import { useMemo, useState } from 'react'
import Link from 'next/link'
import {
  BellRing,
  CircleAlert,
  CircleCheck,
  ClipboardPlus,
  Info,
  ShieldAlert,
  TriangleAlert,
  type LucideIcon,
} from 'lucide-react'

import { Button } from '@/lib/kpmg-dice/components/ui/button'
import { Card, CardContent, CardHeader, CardTitle } from '@/lib/kpmg-dice/components/ui/card'
import { StatTile } from '@/lib/kpmg-dice/components/shared/stat-tile'
import { InitialsAvatar, OwnerChip } from '@/lib/kpmg-dice/components/shared/initials-avatar'
import { ScorePill } from '@/lib/kpmg-dice/components/shared/score-pill'

import { executeWrite, riskDigest, useAgentContext } from '@/lib/kpmg-dice/lib/agents'
import { isAtRisk, weightedValueCr } from '@/lib/kpmg-dice/lib/selectors/overview'
import { useCrmStore } from '@/lib/kpmg-dice/store/crm-store'
import { formatCrore, formatNumber } from '@/lib/kpmg-dice/lib/format'
import type { Severity } from '@/lib/kpmg-dice/types'
import { cn } from '@/lib/kpmg-dice/lib/utils'
import { useReference } from '@/lib/kpmg-dice/data/use-reference'

const SEVERITY: Record<
  Severity,
  { icon: LucideIcon; tone: string; chip: string; rank: number }
> = {
  critical: {
    icon: TriangleAlert,
    tone: 'text-dice-status-danger',
    chip: 'bg-red-50 text-red-700',
    rank: 0,
  },
  high: {
    icon: TriangleAlert,
    tone: 'text-amber-600',
    chip: 'bg-amber-50 text-amber-700',
    rank: 1,
  },
  medium: {
    icon: CircleAlert,
    tone: 'text-amber-600',
    chip: 'bg-amber-50 text-amber-700',
    rank: 2,
  },
  info: {
    icon: Info,
    tone: 'text-kpmg-lightblue',
    chip: 'bg-sky-50 text-sky-700',
    rank: 3,
  },
}

export function RiskAlertsPage() {
  const { reps } = useReference()
  const ctx = useAgentContext()
  const activities = useCrmStore((s) => s.activities)
  const [handled, setHandled] = useState<Record<string, string>>({})

  const alerts = useMemo(
    () =>
      riskDigest(ctx).sort(
        (a, b) => SEVERITY[a.severity].rank - SEVERITY[b.severity].rank,
      ),
    [ctx],
  )

  /** The individual leads behind the aggregate alerts, worst exposure first. */
  const atRiskLeads = useMemo(
    () =>
      ctx.leads
        .filter(isAtRisk)
        .sort((a, b) => weightedValueCr(b) - weightedValueCr(a))
        .slice(0, 12),
    [ctx.leads],
  )

  const totalExposure = useMemo(
    () =>
      Math.round(
        ctx.leads.filter(isAtRisk).reduce((s, l) => s + weightedValueCr(l), 0),
      ),
    [ctx.leads],
  )

  const criticalCount = alerts.filter((a) => a.severity === 'critical').length

  function assignTask(leadId: string) {
    const lead = ctx.leads.find((l) => l.id === leadId)
    if (!lead) return
    const result = executeWrite({
      kind: 'create-task',
      leadId: lead.id,
      subject: `Rescue at-risk lead — ${lead.name}`,
      ownerId: lead.ownerId,
      dueInDays: 1,
      priority: 'High',
    })
    setHandled((h) => ({ ...h, [leadId]: result }))
  }

  function notifyOwner(alertId: string, headline: string) {
    const result = executeWrite({
      kind: 'log-activity',
      object: 'Activity',
      recordId: alertId,
      recordName: 'Risk digest',
      action: 'Owner notified',
      detail: headline,
    })
    setHandled((h) => ({ ...h, [alertId]: result }))
  }

  return (
    <div className="animate-fade-in space-y-4">
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <StatTile
          label="Total exposure"
          value={formatCrore(totalExposure)}
          sub="Probability-weighted revenue at risk"
          icon={ShieldAlert}
          accent="text-dice-status-danger"
          accentBg="bg-dice-status-danger/10"
          danger
        />
        <StatTile
          label="Active alerts"
          value={String(alerts.length)}
          sub={`${criticalCount} critical`}
          icon={BellRing}
        />
        <StatTile
          label="Leads at risk"
          value={formatNumber(ctx.leads.filter(isAtRisk).length)}
          sub="Deep-funnel records with a risk signal"
          icon={CircleAlert}
          accent="text-amber-600"
          accentBg="bg-amber-50"
        />
        <StatTile
          label="Actions taken"
          value={String(activities.length)}
          sub="CRM writes this session"
          icon={CircleCheck}
          accent="text-kpmg-teal"
          accentBg="bg-kpmg-teal/10"
        />
      </div>

      {/* Prioritised alerts */}
      <Card>
        <CardHeader>
          <CardTitle>Prioritised alerts</CardTitle>
          <p className="shrink-0 text-[11.5px] text-slate-400">
            Generated by the Risk Dashboard Agent
          </p>
        </CardHeader>
        <CardContent>
          <ul className="space-y-2.5">
            {alerts.map((alert) => {
              const config = SEVERITY[alert.severity]
              const Icon = config.icon
              const done = handled[alert.id]

              return (
                <li
                  key={alert.id}
                  className="flex flex-wrap items-start gap-3 rounded-xl border border-slate-200 p-4"
                >
                  <Icon
                    className={cn('mt-0.5 size-5 shrink-0', config.tone)}
                    strokeWidth={2.1}
                  />

                  <div className="min-w-[240px] flex-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <p className="text-[13.5px] font-semibold text-slate-900">
                        {alert.headline}
                      </p>
                      <span
                        className={cn(
                          'rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide',
                          config.chip,
                        )}
                      >
                        {alert.severity}
                      </span>
                    </div>
                    <p className="mt-1 text-[12px] text-slate-500">
                      {alert.detail}
                    </p>
                  </div>

                  {alert.impactedRevenueCr !== undefined && (
                    <div className="shrink-0 text-right">
                      <p className="text-[10px] font-semibold uppercase tracking-wider text-slate-400">
                        Impact
                      </p>
                      <p className="nums text-[15px] font-bold text-dice-status-danger">
                        {formatCrore(alert.impactedRevenueCr, { decimals: 1 })}
                      </p>
                    </div>
                  )}

                  <div className="flex shrink-0 items-center gap-2">
                    {done ? (
                      <span className="flex items-center gap-1.5 text-[12px] font-semibold text-dice-status-success">
                        <CircleCheck className="size-4" />
                        Notified
                      </span>
                    ) : (
                      <Button
                        size="sm"
                        variant="outline"
                        onClick={() => notifyOwner(alert.id, alert.headline)}
                      >
                        <BellRing />
                        Notify
                      </Button>
                    )}
                    {alert.href && (
                      <Button size="sm" variant="ghost" asChild>
                        <Link href={alert.href}>Investigate →</Link>
                      </Button>
                    )}
                  </div>
                </li>
              )
            })}
          </ul>
        </CardContent>
      </Card>

      {/* The leads behind the numbers */}
      <Card>
        <CardHeader>
          <CardTitle>Highest-exposure leads</CardTitle>
          <p className="shrink-0 text-[11.5px] text-slate-400">
            One click assigns a rescue task to the record owner
          </p>
        </CardHeader>
        <CardContent>
          <div className="scrollbar-slim overflow-x-auto">
            <table className="w-full min-w-[820px]">
              <thead>
                <tr className="border-b border-slate-200 text-left">
                  {['Customer', 'Score', 'Stage', 'Why at risk', 'Exposure', 'Owner', ''].map(
                    (h, i) => (
                      <th
                        key={h || i}
                        className={cn(
                          'pb-2 text-[10.5px] font-semibold uppercase tracking-wide text-slate-400',
                          i >= 4 && 'text-right',
                        )}
                      >
                        {h}
                      </th>
                    ),
                  )}
                </tr>
              </thead>
              <tbody>
                {atRiskLeads.map((lead) => {
                  const rep = reps.find((r) => r.id === lead.ownerId)
                  const reason =
                    lead.evidenceStatus === 'contradicted'
                      ? `CRM says "${lead.crmStatus}" with no supporting evidence`
                      : lead.sentiment === 'negative'
                        ? 'Negative call sentiment against an open status'
                        : `Hot lead silent for ${lead.evidence.daysSinceLastActivity} days`

                  return (
                    <tr
                      key={lead.id}
                      className="border-b border-slate-50 last:border-0 hover:bg-slate-50/60"
                    >
                      <td className="py-2.5 pr-3">
                        <Link
                          href={`/agents/kpmg-dice/console/customers/${lead.id}`}
                          className="group flex items-center gap-2.5"
                        >
                          <InitialsAvatar name={lead.name} />
                          <span className="min-w-0">
                            <span className="block truncate text-[12.5px] font-semibold text-slate-900 group-hover:text-kpmg-blue">
                              {lead.name}
                            </span>
                            <span className="block truncate text-[11px] text-slate-500">
                              {lead.preferredLocation} · ₹{lead.budgetCr} Cr
                            </span>
                          </span>
                        </Link>
                      </td>
                      <td className="py-2.5 pr-3">
                        <ScorePill score={lead.score} />
                      </td>
                      <td className="py-2.5 pr-3 text-[12px] capitalize text-slate-600">
                        {lead.stage.replace('-', ' ')}
                      </td>
                      <td className="max-w-[260px] py-2.5 pr-3 text-[11.5px] leading-snug text-slate-500">
                        {reason}
                      </td>
                      <td className="nums py-2.5 text-right text-[12.5px] font-semibold text-dice-status-danger">
                        {formatCrore(Math.round(weightedValueCr(lead) * 10) / 10, {
                          decimals: 1,
                        })}
                      </td>
                      <td className="py-2.5">
                        <div className="flex justify-end">
                          <OwnerChip code={rep?.initials ?? '—'} />
                        </div>
                      </td>
                      <td className="py-2.5 pl-3">
                        <div className="flex justify-end">
                          {handled[lead.id] ? (
                            <span className="flex items-center gap-1 text-[11.5px] font-semibold text-dice-status-success">
                              <CircleCheck className="size-3.5" />
                              Task created
                            </span>
                          ) : (
                            <Button
                              size="sm"
                              variant="outline"
                              onClick={() => assignTask(lead.id)}
                            >
                              <ClipboardPlus />
                              Assign
                            </Button>
                          )}
                        </div>
                      </td>
                    </tr>
                  )
                })}
              </tbody>
            </table>
          </div>
        </CardContent>
      </Card>
    </div>
  )
}
